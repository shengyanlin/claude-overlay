#!/bin/bash
# Build "Claude Overlay.app" — the macOS launcher. What the Desktop / Start Menu shortcut
# is on Windows: something to double-click (or keep in the Dock) that starts the overlay
# with no Terminal window.
#
#     mac-app.sh [destination folder]      (default: the app folder itself)
#
# The bundle is a launcher, not a copy of the app: it holds the icon, an Info.plist and a
# few lines that start the code in THIS folder with this folder's .venv. So it is
# machine-specific (it is in .gitignore, like a .lnk), it keeps working across updates,
# and it must be rebuilt if the app folder moves — update.command does that.
#
# Why a bundle and not just a .command file: a .command opens a Terminal window that
# stays behind, and macOS attributes the overlay's Screen Recording permission to
# whatever launched it — "Terminal" for a script, "Claude Overlay" for this.

OV_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$OV_REPO/mac-common.sh"

DEST="${1:-$OV_REPO}"
APP="$DEST/Claude Overlay.app"
ICON_SRC="$OV_REPO/claude_overlay_2.png"
# The parts of a bundle, as paths inside it - the same in the old one and the new one.
LAUNCHER="Contents/MacOS/ClaudeOverlay"
PLIST="Contents/Info.plist"
ICON="Contents/Resources/AppIcon.icns"
SEAL="Contents/_CodeSignature/CodeResources"    # there once codesign has signed it

if [ ! -d "$DEST" ]; then
  echo "[X] No such folder: $DEST"
  exit 1
fi
# A file (or a dead link) that has the bundle's name is not a launcher of ours to replace.
if [ ! -d "$APP" ] && { [ -e "$APP" ] || [ -L "$APP" ]; }; then
  echo "[X] Could not create $APP"
  echo "    Something that is not a folder already has that name."
  exit 1
fi

# ── the launcher ──
# %q writes the folder so bash reads it back exactly, whatever is in its name (spaces,
# quotes, an ampersand). exec replaces this shell with Python, so the app is one process.
# This file and Info.plist ARE the bundle - without either it won't open - so failing to
# write them fails the build. (The icon and the signature further down are extras.)
# Each is a function that prints the file, because each is wanted twice: to compare with
# the launcher that is already there, and to write the new one.
ov_launcher() {
  echo '#!/bin/bash' &&
  echo '# Generated by mac-app.sh - rebuilt by update.command. Starts the overlay in:' &&
  printf 'REPO=%q\n' "$OV_REPO" &&
  cat <<'LAUNCH'
PY="$REPO/.venv/bin/python"
if [ ! -x "$PY" ] || [ ! -f "$REPO/claude_overlay.py" ]; then
  /usr/bin/osascript -e 'on run argv
display dialog "Claude Overlay cannot start: its app folder has moved or is not set up." & return & return & "Open that folder and double-click setup.command, which rebuilds this launcher:" & return & (item 1 of argv) with title "Claude Overlay" buttons {"OK"} default button 1 with icon stop
end run' "$REPO" >/dev/null 2>&1
  exit 1
fi
cd "$REPO" || exit 1
# Tells config.py this is a Finder/Dock start, so it asks the login shell for its PATH.
# SHLVL can't: bash sets it to 1 here and takes it back to 0 for the exec.
export CLAUDE_OVERLAY_FROM_APP=1
exec "$PY" "$REPO/claude_overlay.py"
LAUNCH
}

# ── Info.plist ──
# LSUIElement: no Dock tile and no menu bar of its own — the overlay is an accessory app
# (it has to be, to float over full-screen apps) and lives in the menu bar instead.
# NSAppleEventsUsageDescription: Claude drives the app you have open through AppleScript;
# macOS refuses that outright, with no prompt, for an app that doesn't declare why.
# The version is the LAUNCHER's, and fixed. It deliberately does not follow the app's:
# the bundle only starts the code in the folder, and whatever changes in here with a
# release changes the bundle's identity with it (see below) - on every update.
ov_plist() {
  cat <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Claude Overlay</string>
  <key>CFBundleDisplayName</key><string>Claude Overlay</string>
  <key>CFBundleIdentifier</key><string>io.github.shengyanlin.claude-overlay</string>
  <key>CFBundleExecutable</key><string>ClaudeOverlay</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSAppleEventsUsageDescription</key>
  <string>Claude Overlay lets Claude work in the app you have open when you ask it to, for example to edit the document on your screen.</string>
</dict>
</plist>
PLIST
}

# ── is the launcher that is there already this one? ──
# macOS remembers Screen Recording and Automation permission per app, and knows an
# ad-hoc signed app (which is all this can be) by the hash of what was signed. Rebuild
# the bundle and it can be a new app to macOS, with the permissions to grant again. So a
# launcher whose two files are already what this build would write is left alone: not
# swapped, not re-signed, not even touched. It changes only when it has to - the app
# folder moved, or a release changed the text above (which costs every user that prompt).
SAME=""
if [ -f "$APP/$LAUNCHER" ] && [ -x "$APP/$LAUNCHER" ] && [ -f "$APP/$PLIST" ] \
   && ov_launcher 2>/dev/null | cmp -s - "$APP/$LAUNCHER" \
   && ov_plist 2>/dev/null | cmp -s - "$APP/$PLIST"; then
  SAME=1
fi
# ...and complete. If it is short of its icon or its signature, go on and see whether
# this build can supply one; that is decided when it has tried, just before the swap.
if [ -n "$SAME" ] && [ -s "$APP/$ICON" ] && [ -f "$APP/$SEAL" ]; then
  echo "[OK] Already up to date: $APP"
  exit 0
fi

# ── build, then swap ──
# The bundle is put together in a hidden folder beside where it goes (same folder, so
# same disk, so moving it into place is a rename) and takes the launcher's name only
# once it is complete. A build that stops halfway - a full disk, no permission - then
# leaves the launcher that was already there exactly as it was, still working.
STAGE=""; NEW=""; OLD=""                # set below; emptied so nothing inherited is used
ov_unstage() {
  # This ends in rm -rf, so: only the folder mktemp made for this run, inside $DEST.
  # Never "" and never anything else, whatever became of the variables.
  case "$STAGE" in "$DEST"/.claude-overlay-app.*) ;; *) return ;; esac
  if [ ! -d "$STAGE" ] || [ -L "$STAGE" ]; then return; fi
  if { [ -d "$OLD" ] || [ -L "$OLD" ]; } && [ ! -e "$APP" ] && [ ! -L "$APP" ]; then
    # The swap moved the old launcher in here and then could not give the new one its
    # name, so nothing has it. Put the old one back - and if even that fails, keep this
    # folder, because removing it would remove the launcher.
    if ! mv "$OLD" "$APP"; then
      echo "[X] The launcher that was there could not be put back. It is now in:"
      echo "      $OLD"
      return
    fi
  fi
  # Past that check the stage holds only what is no longer wanted: a build that failed,
  # or the old launcher now that the new one has its name.
  rm -rf "$STAGE" || echo "[NOTE] Could not remove $STAGE (it is safe to delete)."
}
trap ov_unstage EXIT
trap 'exit 1' HUP INT TERM              # a Ctrl-C or a closed window: clean up, then go

STAGE="$(mktemp -d "$DEST/.claude-overlay-app.XXXXXX")" || {
  echo "[X] Could not create $APP"; exit 1; }
NEW="$STAGE/Claude Overlay.app"         # under its real name: codesign is given a .app
OLD="$STAGE/previous"                   # where the old launcher waits during the swap

mkdir -p "$NEW/Contents/MacOS" "$NEW/Contents/Resources" || {
  echo "[X] Could not create $APP"; exit 1; }

ov_launcher > "$NEW/$LAUNCHER" && chmod 755 "$NEW/$LAUNCHER" || {
  echo "[X] Could not write the launcher in $APP"; exit 1; }
ov_plist > "$NEW/$PLIST" || { echo "[X] Could not write $APP/$PLIST"; exit 1; }

# ── the icon ──
# Drawn from the orb artwork with Pillow (nearest-neighbour: Clawd is pixel art, and a
# smooth resize blurs him), then packed by iconutil. Best-effort: with no icon the bundle
# still launches, it just shows the generic app icon.
if ov_python_ok "$OV_PY" && [ -f "$ICON_SRC" ] && command -v iconutil >/dev/null 2>&1 \
   && ICONTMP="$(mktemp -d)"; then      # checked: the rm -rf below must never see ""
  ICONSET="$ICONTMP/AppIcon.iconset"
  mkdir -p "$ICONSET"
  if "$OV_PY" - "$ICON_SRC" "$ICONSET" <<'PY' >/dev/null 2>&1
import sys
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
art = Image.open(src).convert("RGBA")
for size in (16, 32, 128, 256, 512):
    for scale in (1, 2):
        px = size * scale
        inner = int(px * 0.80)                       # the breathing room macOS icons have
        ratio = min(inner / art.width, inner / art.height)
        w, h = max(1, round(art.width * ratio)), max(1, round(art.height * ratio))
        canvas = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        canvas.alpha_composite(art.resize((w, h), Image.NEAREST), ((px - w) // 2, (px - h) // 2))
        canvas.save(f"{out}/icon_{size}x{size}{'@2x' if scale == 2 else ''}.png")
PY
  then
    iconutil -c icns "$ICONSET" -o "$NEW/$ICON" >/dev/null 2>&1
  fi
  rm -rf "$ICONTMP"
fi
# No icon this time (Pillow or iconutil let it down) but the launcher being replaced has
# one: carry it over, as rebuilding in place used to, rather than swap in a blank.
if [ ! -s "$NEW/$ICON" ] && [ -s "$APP/$ICON" ]; then
  cp "$APP/$ICON" "$NEW/$ICON" 2>/dev/null
fi

# An ad-hoc signature gives the bundle an identity for the permissions macOS remembers
# per app - one that lasts for as long as the bundle is left as it is, hence the check
# above. Best-effort: unsigned works too, on the Mac that built it. Signed before the
# swap, so what takes the launcher's name is already finished.
codesign --force --sign - "$NEW" >/dev/null 2>&1 || true

# The launcher that is there has the right two files and was only short of its icon or
# its signature. If this build came out no better on that count, swapping it in would
# gain nothing - and would do so again on every update. Leave the old one be.
if [ -n "$SAME" ] && { [ -s "$APP/$ICON" ] || [ ! -s "$NEW/$ICON" ]; } \
   && { [ -f "$APP/$SEAL" ] || [ ! -f "$NEW/$SEAL" ]; }; then
  echo "[OK] Already up to date: $APP"
  exit 0
fi

# ── the swap ──
# A folder can't be replaced in one step, so it is two renames: the old launcher steps
# aside into the stage (which is what ov_unstage clears), then the new one takes its
# name. Nothing has that name in between - so if the second rename fails, ov_unstage
# moves the old one back; and a Ctrl-C or a closed window no longer stops the script
# (or the mv it is waiting for) from here on: what is left takes no time to finish.
trap '' HUP INT TERM
if [ -d "$APP" ] && ! mv "$APP" "$OLD"; then
  echo "[X] Could not replace $APP"
  echo "    It could not be moved out of the way, so it is still the launcher it was."
  exit 1
fi
# -e: mv would put the new bundle INSIDE a folder that turned up under that name.
if [ -e "$APP" ] || [ -L "$APP" ] || ! mv "$NEW" "$APP"; then
  echo "[X] Could not move the new launcher to $APP"
  exit 1
fi
touch "$APP"          # so Finder notices a rebuilt icon

echo "[OK] Built: $APP"
